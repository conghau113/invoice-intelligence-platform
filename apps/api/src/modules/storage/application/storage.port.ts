import type { Readable } from 'node:stream';

export const STORAGE_PORT = Symbol('STORAGE_PORT');

export interface StoredObject {
  key: string;
  /** Bytes written. */
  size: number;
  /** Lowercase hex sha256 of the bytes, computed while streaming (T2.3 uses it as content_hash). */
  sha256: string;
}

export interface ObjectStat {
  size: number;
}

/** The key is not a safe relative path of plain segments (e.g. contains `..`). */
export class InvalidStorageKeyError extends Error {
  constructor() {
    super('Invalid storage key');
    this.name = 'InvalidStorageKeyError';
  }
}

export class ObjectNotFoundError extends Error {
  constructor() {
    super('Object not found');
    this.name = 'ObjectNotFoundError';
  }
}

/**
 * Where uploaded files live (ADR 0017). The domain only knows this interface; LocalFs implements
 * it today and an S3/SeaweedFS adapter can replace it (O1) as long as it passes the contract test.
 * Keys are `/`-separated relative paths generated by the server, never by the user.
 */
export interface StoragePort {
  /**
   * Streams `data` to `key`, replacing any existing object. Never leaves a partial object behind:
   * if the stream fails, nothing is stored and the error is rethrown.
   */
  put(key: string, data: Readable): Promise<StoredObject>;
  /** @throws ObjectNotFoundError */
  get(key: string): Promise<Readable>;
  /** Deleting a missing key is not an error (idempotent). */
  delete(key: string): Promise<void>;
  /** `null` when the key does not exist. */
  stat(key: string): Promise<ObjectStat | null>;
}
